#!/bin/bash
# =============================================================================
# Entrypoint script для Django приложения
# =============================================================================
# Выполняется при каждом запуске контейнера
# =============================================================================

set -e

echo "🚀 Starting Management System Backend..."

# -----------------------------------------------------------------------------
# Ожидание готовности PostgreSQL
# -----------------------------------------------------------------------------
echo "⏳ Waiting for PostgreSQL..."

while ! nc -z ${DB_HOST:-db} ${DB_PORT:-5432}; do
    sleep 1
done

echo "✅ PostgreSQL is ready!"

# -----------------------------------------------------------------------------
# Применение миграций
# -----------------------------------------------------------------------------
echo "📦 Creating and applying database migrations..."
python manage.py makemigrations accounts --noinput
python manage.py makemigrations core projects tasks research notifications analytics --noinput
python manage.py migrate --noinput

# -----------------------------------------------------------------------------
# Сбор статических файлов (для production)
# -----------------------------------------------------------------------------
if [ "$DJANGO_ENV" = "production" ]; then
    echo "📁 Collecting static files..."
    python manage.py collectstatic --noinput
fi

# -----------------------------------------------------------------------------
# Создание seed данных (если включено)
# -----------------------------------------------------------------------------
if [ "$CREATE_SEED_DATA" = "True" ]; then
    echo "🌱 Creating seed data..."
    python manage.py seed_data || true
fi

echo "✨ Backend is ready!"

# -----------------------------------------------------------------------------
# Запуск переданной команды
# -----------------------------------------------------------------------------
exec "$@"
